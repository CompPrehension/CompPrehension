/**
 * Соглашения о маппингах.
 * <p>
 * В проекте три формы одних и тех же данных: {@code *Entity} — строка в базе,
 * {@code *Data} — модель, которой говорят сервисы, {@code *Dto} — контракт HTTP.
 * Переходы между ними разрешены только три: {@code Entity → Data}, {@code Data → Entity}
 * и {@code Data → Dto}. Прямого {@code Entity → Dto} нет.
 * <p>
 * Правила, которые к ним применяются (проверяются в модуле {@code architecture-tests},
 * класс {@code MapperConventionTest}):
 * <ol>
 *   <li>Один класс — один предмет маппинга. Оба направления по одному предмету
 *       (прочитать сущность в модель и применить модель обратно) могут жить вместе.
 *       Ни god-классов, ни перегрузок по разным предметам: имя метода перестаёт
 *       что-либо значить, когда их пять.</li>
 *   <li>Всякий маппер — это {@link org.vstu.compprehension.mappers.Mapping}. Маркер
 *       нужен затем, чтобы «маппер» оставался типом, а не суффиксом в имени класса.</li>
 *   <li>У маппинга с одним источником — готовый обобщённый интерфейс:
 *       {@link org.vstu.compprehension.mappers.Mapper#map} создаёт цель,
 *       {@link org.vstu.compprehension.mappers.UpdateMapper#apply} правит уже
 *       существующую. Второй нужен для управляемых JPA-сущностей: подменять экземпляр
 *       нельзя, иначе теряются идентичность и dirty checking.</li>
 *   <li>Если входов больше одного, маппер объявляет собственный интерфейс, наследующий
 *       {@code Mapping}, и берёт аргументы как есть. Заворачивать их в record-обёртку
 *       ради обобщённого интерфейса не нужно — обёртка ничего не проверяет, а читаемость
 *       на вызове портит. Прежде чем заводить такой интерфейс, стоит проверить, не знает
 *       ли недостающее значение сам запрос: если знает — правильнее расширить проекцию.</li>
 *   <li>Методы называются только {@code map} и {@code apply}. У {@code apply} цель —
 *       последний аргумент, и возвращает он {@code void}. {@code map} не возвращает
 *       коллекцию: для набора есть
 *       {@link org.vstu.compprehension.mappers.Mapper#mapAll}.</li>
 *   <li>Маппер — бин с конструкторным внедрением, а не статический метод: иначе его
 *       не подменить и не покрыть тестом.</li>
 *   <li>Потребитель внедряет маппер по интерфейсу, а не по классу-реализации. Поэтому
 *       реализации не публичны — компилятор поддерживает правило сам. И сам интерфейс
 *       публичен только тогда, когда его называют за пределами своего пакета.</li>
 *   <li>Маппер чист: ни репозиториев, ни сервисов, ни доменной логики. Единственная
 *       разрешённая зависимость — другие мапперы.</li>
 *   <li>Предмет маппинга и результат никогда не {@code null}: отсутствие значения —
 *       забота вызывающего ({@code Optional.map(mapper::map)}). Необязательный
 *       контекст-аргумент — другое дело: связь, которой в принципе может не быть,
 *       через {@code Optional} у вызывающего не выразить.</li>
 *   <li>Мапперы {@code Entity ↔ Data} лежат в {@code repositories.mappers}, мапперы
 *       в сторону представления — во {@code frontend.mappers}. Здесь, в {@code mappers},
 *       только интерфейсы. Для первых расположение содержательно: сущность не выходит
 *       за пределы слоя доступа к данным, поэтому снаружи такой маппинг и не выразить —
 *       правило «мапит тот, кто фетчил» удерживается границей слоя, а не договорённостью.</li>
 *   <li>{@code *Dto} собирает только маппер: ни сервис, ни фасад, ни контроллер
 *       не вызывают конструктор или билдер DTO.</li>
 *   <li>{@code *DataRepository} не объявляет маппинг-методов вовсе. Признак маппинга —
 *       пересечение границы: в сигнатуре встретились и персистентный тип, и модель данных.</li>
 * </ol>
 */
package org.vstu.compprehension.mappers;
