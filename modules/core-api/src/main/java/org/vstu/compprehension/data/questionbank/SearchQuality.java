package org.vstu.compprehension.data.questionbank;

/**
 * Насколько хорош оказался найденный в банке вопрос.
 */
public enum SearchQuality {
    /** Лучшие из тех, что этому студенту ещё не показывали. */
    BestUnused,
    /** Лучшие, включая уже показанные. */
    BestUsed,
    /** Подходящие по всем критериям, но не лучшие. */
    Normal,
    /** Хоть сколько-нибудь подходящие: часть критериев не выполнена. */
    Relaxed,
}
