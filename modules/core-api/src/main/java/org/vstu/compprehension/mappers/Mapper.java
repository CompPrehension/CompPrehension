package org.vstu.compprehension.mappers;

import org.jetbrains.annotations.NotNull;

import java.util.Collection;
import java.util.List;

/**
 * Перенос одного значения в новое значение другого типа.
 * <p>
 * Форма для целей, которые нельзя изменить после создания: {@code record}-моделей данных
 * и DTO, собираемых билдером. Если цель уже существует и её надо обновить на месте —
 * это {@link UpdateMapper}, а не этот интерфейс.
 * <p>
 * Реализация обязана быть чистой функцией источника: ни запросов, ни сервисов, ни часов,
 * ни случайности. Всё, чего маппингу не хватает, приходит внутри {@code S} — при
 * необходимости в виде record'а, собирающего источник и его контекст. Такой record —
 * это ещё и явный контракт «что должно быть подгружено», который компилятор проверяет
 * за нас: ленивая связь, не попавшая в источник, просто не окажется маппингу доступна.
 *
 * @param <S> тип источника
 * @param <D> тип цели
 * @see UpdateMapper
 * @see Mapping
 */
public interface Mapper<S, D> extends Mapping {

    /** Новое значение по источнику. */
    @NotNull D map(@NotNull S source);

    /**
     * То же самое для набора источников.
     * <p>
     * Живёт здесь, чтобы мапперам не приходилось объявлять собственные методы
     * над коллекциями: маппер знает про одно значение и только про него.
     */
    default @NotNull List<D> mapAll(@NotNull Collection<? extends S> sources) {
        return sources.stream().map(this::map).toList();
    }
}
