/**
 * Доступ к данным: единственное место, где JPA-сущности превращаются в {@code *Data}.
 *
 * <h2>Зачем слой</h2>
 * Маппер, принимающий сущность, не знает, какой выборкой её подняли. Из-за этого он
 * вынужден заполнять поля «если получится», и один и тот же метод под разными запросами
 * даёт разный результат: {@code toData(InteractionEntity)} проставлял вопрос, когда его
 * звали из вопроса, и оставлял {@code null}, когда из шага цепочки. Дальше это выходило
 * NPE в домене.
 * <p>
 * Здесь запрос и маппинг живут вместе и правятся вместе. Поэтому маппинг может быть
 * <b>тотальным</b>: он либо возвращает полностью заполненные данные, либо падает.
 *
 * <h2>Правила</h2>
 * <ul>
 *   <li>На входе и выходе публичных методов — только {@code *Data} и примитивы.
 *       Ни одна сущность наружу не выходит.</li>
 *   <li>Маппинг Entity → Data не публичен: он существует только внутри классов этого
 *       пакета. Позвать его с недогруженной сущностью неоткуда.</li>
 *   <li>Запросы фиксируют форму выборки целиком. Число запросов на вызов постоянно и
 *       не зависит от размера данных.</li>
 *   <li>Одна {@code *Data} — одна форма. Не бывает «того же класса, но заполненного
 *       наполовину»: если поле объявлено, оно заполнено.</li>
 *   <li>Запись — методами, названными по намерению ({@code createStep}), а не общим
 *       {@code save(data)}: перезапись агрегата целиком стирает то, чего в данных нет.</li>
 *   <li>Обращаться сюда могут сервисы. Домены и стратегии — только через сервисы.</li>
 * </ul>
 *
 * <h2>Чего слой не гарантирует</h2>
 * Забытый {@code join fetch} внутри открытой транзакции исключения не даст: Hibernate
 * молча сходит в базу. Строгость ловит недозаполненность, но не N+1. Единственная защита
 * от него — счётчик запросов в тесте на каждый метод.
 */
